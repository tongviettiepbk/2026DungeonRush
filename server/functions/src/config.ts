// elw(boss, tier): kẹp index như gốc.
export function getBossHp(bossNumber: number, tier: number): number {
  const t = Math.min(Math.max(tier - 1, 0), MAX_TIER - 1);
  const b = Math.min(Math.max(bossNumber - 1, 0), MAX_BOSS_COUNT - 1);
  return BOSS_HP_TABLE[t][b];
}

// elx(_, tier).
export function getBossDamage(tier: number): number {
  const t = Math.min(Math.max(tier - 1, 0), BOSS_DAMAGE_BY_TIER.length - 1);
  return BOSS_DAMAGE_BY_TIER[t];
}
